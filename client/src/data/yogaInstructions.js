// Helper function to get instructions for a pose
export const getPoseInstructions = (poseName) => {
  if (!poseName) return null;
  
  const normalizedName = poseName.toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
  
  console.log('Looking for pose instructions:', poseName, 'normalized:', normalizedName);
  
  // Try exact match first
  if (yogaInstructions[normalizedName]) {
    console.log('Found exact match:', yogaInstructions[normalizedName]);
    return yogaInstructions[normalizedName];
  }
  
  // Try partial matches
  for (const [key, instructions] of Object.entries(yogaInstructions)) {
    if (normalizedName.includes(key) || key.includes(normalizedName)) {
      console.log('Found partial match:', key, instructions);
      return instructions;
    }
  }
  
  // Try matching by pose name variations
  const poseVariations = {
    'boat': 'boat',
    'bow': 'bow',
    'bridge': 'bridge',
    'mountain': 'mountain',
    'downward-facing-dog': 'downward-facing-dog',
    'child': 'child',
    'warrior-i': 'warrior-i',
    'warrior-ii': 'warrior-ii',
    'tree': 'tree',
    'cobra': 'cobra',
    'plank': 'plank',
    'easy-pose': 'easy-pose',
    'seated-forward-bend': 'seated-forward-bend',
    'cat': 'cat',
    'chair': 'chair',
    'extended-puppy': 'extended-puppy',
    'half-boat': 'half-boat'
  };
  
  const variation = poseVariations[normalizedName];
  if (variation && yogaInstructions[variation]) {
    console.log('Found variation match:', variation, yogaInstructions[variation]);
    return yogaInstructions[variation];
  }
  
  // Fallback: provide generic, safe instructions so every pose has guidance
  console.log('No instructions found for:', poseName, '— returning generic instructions');
  return {
    name: poseName,
    sanskrit: '',
    level: 'beginner',
    duration: '30-60 seconds',
    benefits: [
      'Improves body awareness',
      'Encourages mindful breathing',
      'Enhances posture and stability'
    ],
    instructions: [
      'Start with a brief warm-up and settle your breath',
      'Move into the pose slowly with control and alignment',
      'Keep breathing deeply through the nose (inhale and exhale evenly)',
      'Adjust stance and joint angles to stay pain-free and comfortable',
      'Hold for a few breaths while maintaining a neutral, long spine',
      'To exit, release gradually and rest before repeating if desired'
    ],
    tips: [
      'Never push into sharp pain; back off if uncomfortable',
      'Engage the core lightly to support the lower back',
      'Use props (blocks, strap, wall) to improve alignment and ease'
    ],
    modifications: [
      'Shorten the stance or range of motion',
      'Use a wall or chair for balance/support',
      'Place a folded blanket under sensitive joints'
    ]
  };
};

// Helper function to get all poses by level
export const getPosesByLevel = (level) => {
  return Object.values(yogaInstructions).filter(pose => pose.level === level);
};

// Helper function to search poses
export const searchPoses = (query) => {
  const searchTerm = query.toLowerCase();
  return Object.values(yogaInstructions).filter(pose => 
    pose.name.toLowerCase().includes(searchTerm) ||
    pose.sanskrit.toLowerCase().includes(searchTerm) ||
    pose.benefits.some(benefit => benefit.toLowerCase().includes(searchTerm))
  );
};
